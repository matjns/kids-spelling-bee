#!/usr/bin/env python3
"""Turn Data/easy.txt, medium.txt, advanced.txt (word|definition|sentence)
into Sources/SpellingBeeCore/WordListData.swift. Run from the repo root."""
import json
from pathlib import Path
root = Path(__file__).resolve().parent.parent
words = []
for tier in ["easy", "medium", "advanced"]:
    for line in (root / "Data" / f"{tier}.txt").read_text().splitlines():
        if not line.strip():
            continue
        word, definition, sentence = line.split("|")
        words.append({"word": word, "definition": definition, "sentence": sentence, "tier": tier})
body = json.dumps(words, ensure_ascii=False, indent=0)
out = root / "Sources" / "SpellingBeeCore" / "WordListData.swift"
out.write_text("// Generated by Data/generate.py. Edit the .txt files, not this file.\n"
               "enum WordListData {\n    static let json = #\"\"\"\n" + body + "\n\"\"\"#\n}\n")
print(len(words), "words")
